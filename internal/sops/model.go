// Model is the declarative source of every recipient in .sops.yaml.
type Model struct {
	// Admins are PGP fingerprints that can decrypt everything.
	Admins []string
	// Sessions are age recipients that can decrypt everything except
	// vars/admin.
	Sessions []string
	// Machines maps a machine to the age recipient derived from its host key.
	Machines map[string]string
	// Groups maps a group to its member machines.
	Groups map[string][]string
}

// LoadModel reads admins and sessions from the generic machine rule in
// confPath and machine recipients from the host public keys present under
// flakeDir. groups normally comes from the hosts file.
func LoadModel(confPath, flakeDir string, groups map[string][]string) (Model, error) {
	cfg, err := loadSopsYAML(confPath)
	if err != nil {
		return Model{}, err
	}
	generic, err := findGenericGroup(cfg, vars.GenericMachineRegex)
	if err != nil {
		return Model{}, err
	}
	pubs, err := filepath.Glob(vars.MachineHostKeyPubGlob(flakeDir))
	if err != nil {
		return Model{}, errors.Wrap(err, "glob host public keys")
	}
	machines := make(map[string]string, len(pubs))
	for _, pub := range pubs {
		line, err := os.ReadFile(pub)
		if err != nil {
			return Model{}, errors.Wrapf(err, "read %s", pub)
		}
		age, err := sshkey.ToAge(line)
		if err != nil {
			return Model{}, errors.Wrapf(err, "derive age key from %s", pub)
		}
		machines[vars.MachineFromHostKeyPubPath(pub)] = age
	}
	return Model{
		Admins:   generic.PGP,
		Sessions: generic.Age,
		Machines: machines,
		Groups:   groups,
	}, nil
}

func (m Model) validate() error {
	if len(NewRecipients(m.Admins, nil).PGP) == 0 {
		return errors.New("at least one admin PGP recipient is required")
	}
	for machine := range m.Machines {
		if !vars.ValidName(machine) {
			return errors.Errorf("invalid machine name %q", machine)
		}
		if machine == vars.SharedDirName {
			return errors.Errorf("machine name %q is reserved for group secrets", machine)
		}
	}
	for group := range m.Groups {
		if !vars.ValidName(group) {
			return errors.Errorf("invalid group name %q", group)
		}
	}
	return nil
}

// DesiredRules returns the complete creation rule list for m. Rules in
// current that this tool does not own are kept, in their original order,
// after the per-machine and per-group rules and before the generic fallbacks.
func DesiredRules(m Model, current []creationRule) ([]creationRule, error) {
	if err := m.validate(); err != nil {
		return nil, err
	}
	everything := NewRecipients(m.Admins, m.Sessions)
	group := func(r Recipients) []keyGroup {
		return []keyGroup{{PGP: r.PGP, Age: r.Age}}
	}

	machines := sortedKeys(m.Machines)
	var rules []creationRule
	for _, machine := range machines {
		r := NewRecipients(everything.PGP, append(append([]string{}, everything.Age...), m.Machines[machine]))
		rules = append(rules, creationRule{PathRegex: vars.MachineVarsRegex(machine), KeyGroups: group(r)})
	}
	for _, machine := range machines {
		r := NewRecipients(everything.PGP, append(append([]string{}, everything.Age...), m.Machines[machine]))
		rules = append(rules, creationRule{PathRegex: vars.MachineSecretsRegex(machine), KeyGroups: group(r)})
	}
	for _, name := range sortedKeys(m.Groups) {
		ages := append([]string{}, everything.Age...)
		for _, member := range m.Groups[name] {
			if age, ok := m.Machines[member]; ok {
				ages = append(ages, age)
			}
		}
		rules = append(rules, creationRule{PathRegex: vars.SharedSecretsRegex(name), KeyGroups: group(NewRecipients(everything.PGP, ages))})
	}
	for _, r := range current {
		if !ownedRule(r.PathRegex) {
			rules = append(rules, r)
		}
	}
	rules = append(rules,
		creationRule{PathRegex: vars.GenericMachineRegex, KeyGroups: group(everything)},
		creationRule{PathRegex: vars.GenericSharedRegex, KeyGroups: group(everything)},
		creationRule{PathRegex: vars.AdminVarsRegex, KeyGroups: group(NewRecipients(everything.PGP, nil))},
	)
	return rules, nil
}

// ownedRule reports whether a rule is generated by DesiredRules.
func ownedRule(regex string) bool {
	switch regex {
	case vars.GenericMachineRegex, vars.GenericSharedRegex, vars.AdminVarsRegex:
		return true
	}
	if name, ok := parsePerGroupSharedRegex(regex); ok {
		return vars.ValidName(name)
	}
	const prefix = "vars/secrets/"
	if !strings.HasPrefix(regex, prefix) {
		return false
	}
	rest := regex[len(prefix):]
	for _, suffix := range []string{`\.yaml$`, `/.+$`} {
		if name, ok := strings.CutSuffix(rest, suffix); ok && vars.ValidName(name) {
			return true
		}
	}
	return false
}

// Plan is the set of changes needed to make .sops.yaml and every encrypted
// file match a Model.
type Plan struct {
	Rules        []creationRule
	RulesChanged bool
	// Rekey lists files whose recorded recipients differ from their rule.
	Rekey []string
}

// Empty reports whether nothing needs to change.
func (p Plan) Empty() bool {
	return !p.RulesChanged && len(p.Rekey) == 0
}

// MakePlan compares confPath and the recipients recorded in every encrypted
// file under flakeDir against m. It reads no secret material.
func MakePlan(confPath, flakeDir string, m Model) (Plan, error) {
	cfg, err := loadSopsYAML(confPath)
	if err != nil {
		return Plan{}, err
	}
	rules, err := DesiredRules(m, cfg.CreationRules)
	if err != nil {
		return Plan{}, err
	}
	plan := Plan{Rules: rules, RulesChanged: !ruleListsEqual(cfg.CreationRules, rules)}

	confDir, err := filepath.Abs(filepath.Dir(confPath))
	if err != nil {
		return Plan{}, err
	}
	files, err := ListEncryptedFiles(flakeDir)
	if err != nil {
		return Plan{}, err
	}
	sort.Strings(files)
	for _, path := range files {
		rule, err := matchRule(rules, confDir, path)
		if err != nil {
			return Plan{}, err
		}
		have, err := ReadRecipients(path)
		if err != nil {
			return Plan{}, err
		}
		if !have.Equal(NewRecipients(rule.KeyGroups[0].PGP, rule.KeyGroups[0].Age)) {
			plan.Rekey = append(plan.Rekey, path)
		}
	}
	return plan, nil
}

// Apply writes the planned rules and re-keys the planned files. A failure
// part-way is safe: the next MakePlan picks up whatever is still out of date.
func Apply(confPath string, p Plan, updateFn func(confPath, filePath string) error) error {
	if p.RulesChanged {
		if err := writeSopsYAML(confPath, sopsYAML{CreationRules: p.Rules}); err != nil {
			return err
		}
		log.Info().Msg("updated .sops.yaml")
	}
	for i, path := range p.Rekey {
		log.Info().Int("index", i+1).Int("total", len(p.Rekey)).Str("file", path).Msg("re-encrypting secret with updated recipients")
		if err := updateFn(confPath, path); err != nil {
			return errors.Wrapf(err, "updatekeys %s", path)
		}
	}
	return nil
}

// Sync makes .sops.yaml and every encrypted file match m.
func Sync(confPath, flakeDir string, m Model, updateFn func(confPath, filePath string) error) (Plan, error) {
	p, err := MakePlan(confPath, flakeDir, m)
	if err != nil {
		return Plan{}, err
	}
	return p, Apply(confPath, p, updateFn)
}

// matchRule mirrors how sops selects a creation rule: the path relative to
// the config directory is matched against each path_regex in order.
func matchRule(rules []creationRule, confDir, path string) (creationRule, error) {
	abs, err := filepath.Abs(path)
	if err != nil {
		return creationRule{}, err
	}
	rel := strings.TrimPrefix(abs, confDir+string(filepath.Separator))
	for _, r := range rules {
		re, err := regexp.Compile(r.PathRegex)
		if err != nil {
			return creationRule{}, errors.Wrapf(err, "compile path_regex %q", r.PathRegex)
		}
		if re.MatchString(rel) {
			if len(r.KeyGroups) != 1 {
				return creationRule{}, errors.Errorf("rule %q for %s has %d key groups, expected 1", r.PathRegex, path, len(r.KeyGroups))
			}
			return r, nil
		}
	}
	return creationRule{}, errors.Errorf("no creation rule matches %s", path)
}

func ruleListsEqual(a, b []creationRule) bool {
	if len(a) != len(b) {
		return false
	}
	for i := range a {
		if a[i].PGP != b[i].PGP || a[i].Age != b[i].Age || !rulesEqual(a[i], b[i]) {
			return false
		}
	}
	return true
}

func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}
